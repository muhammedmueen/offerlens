import { readFile } from 'node:fs/promises';
import { MAX_EXTRACT_TEXT_CHARS, MIN_EXTRACTED_TEXT_CHARS } from '@/config/constants.js';

/**
 * Read the text layer out of a PDF, without OCR (plan task 21c, part A).
 *
 * ── WHY THIS EXISTS ───────────────────────────────────────────────────────────
 * Every PDF upload used to fail. `ocr.worker` routed anything that was not `.txt` to
 * `GoogleVisionOcrProvider.extractText`, which calls `textDetection` — an image endpoint. A PDF
 * is not an image format, so it failed on format grounds even before this project's Cloud Vision
 * billing was disabled. Verified by generating a text-layer PDF, uploading it, and watching the
 * offer go FAILED. That left pasted text and `.txt` as the only working paths, while PDF is how
 * offer letters actually arrive.
 *
 * Most offer letters are generated by software and carry an embedded text layer. Reading it is
 * strictly better than OCR for those files: no network call, no vendor, no per-page cost, and the
 * text is EXACT rather than recognised — so `ocrConfidence` stays null and task 11 does not
 * downgrade every field the way it must for a scan.
 *
 * Genuinely scanned PDFs have no text layer and still need OCR. That is part B, and it is blocked
 * on billing; this module's job is to tell the two apart.
 *
 * ── WHY pdfjs-dist DIRECTLY ───────────────────────────────────────────────────
 * `unpdf` was the first choice — it is the modern, actively maintained wrapper and is built for
 * exactly this. Its bundled pdfjs threw `DataCloneError: Cannot transfer object of unsupported
 * type` from `LoopbackPort.postMessage` on Node 24, as an unhandled rejection that killed the
 * process rather than an error a caller could catch. `pdf-parse@2` exports a `PDFParse` class
 * rather than the function its docs imply. Both wrap pdfjs, so using pdfjs's own legacy build
 * removes a layer instead of adding one, and lets the worker options be set explicitly.
 */

export type PdfTextResult =
    /** A usable text layer. */
    | { kind: 'text'; text: string; pages: number }
    /** Valid PDF, but effectively no text — a scan or a photo saved as a PDF. Needs OCR. */
    | { kind: 'no-text-layer'; pages: number }
    /** Password-protected. Common in Indian HR: letters locked with a PAN or date of birth. */
    | { kind: 'encrypted' }
    /** Not a PDF at all, so this module has no opinion. The caller should try OCR. */
    | { kind: 'not-pdf' }
    | { kind: 'unreadable'; reason: string };

/**
 * A PDF starts with `%PDF-`.
 *
 * Sniffed rather than trusting the extension or the declared mime type, both of which come from
 * the uploader. A PDF named `.jpg` should still be read as a PDF, and a JPEG named `.pdf` should
 * not be handed to a PDF parser.
 */
export function looksLikePdf(head: Uint8Array): boolean {
    const magic = [0x25, 0x50, 0x44, 0x46, 0x2d]; // %PDF-
    return head.length >= magic.length && magic.every((byte, i) => head[i] === byte);
}

/**
 * Hard cap on pages read.
 *
 * A public upload endpoint should not let a 5,000-page file decide how long a worker runs. Offer
 * letters are one to five pages; anything past this is either not an offer letter or has already
 * given us more than enough to analyse.
 */
const MAX_PAGES = 30;

/** Page text, with pdfjs's own line breaks preserved. */
function pageToText(items: Array<{ str?: string; hasEOL?: boolean }>): string {
    return items
        .map((item) => (typeof item.str === 'string' ? item.str + (item.hasEOL ? '\n' : '') : ''))
        .join('');
}

export async function extractPdfText(filePath: string): Promise<PdfTextResult> {
    let bytes: Buffer;
    try {
        bytes = await readFile(filePath);
    } catch (error) {
        return { kind: 'unreadable', reason: `could not read the file: ${(error as Error).message}` };
    }

    if (!looksLikePdf(bytes.subarray(0, 5))) return { kind: 'not-pdf' };

    // Imported here rather than at module load: pdfjs is several megabytes and only uploads that
    // are actually PDFs need it. The legacy build is the one that runs outside a browser.
    const pdfjs = await import('pdfjs-dist/legacy/build/pdf.mjs');

    const loading = pdfjs.getDocument({
        // A copy, not a view onto Node's shared Buffer pool: pdfjs takes ownership of the buffer
        // it is given and may detach it.
        data: new Uint8Array(bytes),
        // No worker thread and no network fetches for fonts. There is no `isEvalSupported` to
        // set: pdfjs 6 removed it along with its use of eval, so that hardening is now the
        // library's default rather than ours to request.
        useWorkerFetch: false,
        useSystemFonts: true,
    });

    let doc;
    try {
        doc = await loading.promise;
    } catch (error) {
        const name = (error as { name?: string })?.name ?? '';
        if (name === 'PasswordException') return { kind: 'encrypted' };
        return { kind: 'unreadable', reason: (error as Error).message };
    }

    try {
        const pageCount = doc.numPages;
        const readable = Math.min(pageCount, MAX_PAGES);
        const pages: string[] = [];
        let total = 0;

        for (let n = 1; n <= readable; n++) {
            const page = await doc.getPage(n);
            const content = await page.getTextContent();
            const text = pageToText(content.items as Array<{ str?: string; hasEOL?: boolean }>);

            pages.push(text);
            total += text.length;

            // Stop once there is more than the pipeline will accept anyway. The analysis prompt
            // is capped at the same number, so reading further would cost time to produce text
            // that gets truncated.
            if (total >= MAX_EXTRACT_TEXT_CHARS) break;
        }

        const joined = pages.join('\n\n').trim();

        // One absolute floor, and deliberately the SAME constant the worker uses to decide there
        // is nothing to analyse. A first pass used a per-page average instead, which was both a
        // second threshold for one idea — the mistake task 21d had just finished removing — and
        // wrong in the direction that hurts: it rejected a two-page letter with sparse pages as
        // "looks like a scan", which is a dead end for a user holding a perfectly legible file.
        //
        // Being too permissive costs one thin analysis. Being too strict costs the upload.
        if (joined.length < MIN_EXTRACTED_TEXT_CHARS) {
            return { kind: 'no-text-layer', pages: pageCount };
        }

        return {
            kind: 'text',
            text: joined.slice(0, MAX_EXTRACT_TEXT_CHARS),
            pages: pageCount,
        };
    } catch (error) {
        return { kind: 'unreadable', reason: (error as Error).message };
    } finally {
        // `destroy()` is on the loading task, not the document proxy. Without it pdfjs keeps the
        // parsed structure and its worker alive, and this runs on every upload.
        await loading.destroy().catch(() => { });
    }
}
