import jsPDF from 'jspdf';
import { AnalysisResult } from '@/context/OfferContext';

/**
 * PDF Generator
 * Requirements: 2.5
 * 
 * Generates a PDF report from analysis results
 * Allows users to download and store their analysis locally
 */

export function generateAnalysisPDF(analysis: AnalysisResult): void {
  const doc = new jsPDF();
  const { offerData, redFlags, salaryComparison, takeHome, negotiationSuggestions } = analysis;
  
  let yPosition = 20;
  const lineHeight = 7;
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 20;
  const maxWidth = pageWidth - 2 * margin;

  // Helper function to add text with word wrap
  const addText = (text: string, fontSize: number = 10, isBold: boolean = false) => {
    doc.setFontSize(fontSize);
    if (isBold) {
      doc.setFont('helvetica', 'bold');
    } else {
      doc.setFont('helvetica', 'normal');
    }
    
    const lines = doc.splitTextToSize(text, maxWidth);
    lines.forEach((line: string) => {
      if (yPosition > 280) {
        doc.addPage();
        yPosition = 20;
      }
      doc.text(line, margin, yPosition);
      yPosition += lineHeight;
    });
  };

  // Helper function to add spacing
  const addSpacing = (space: number = 5) => {
    yPosition += space;
  };

  // Title
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text('OfferLens Analysis Report', margin, yPosition);
  yPosition += 15;

  // Date
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`Generated: ${new Date().toLocaleDateString()}`, margin, yPosition);
  yPosition += 10;

  // Offer Details Section
  addText('OFFER DETAILS', 14, true);
  addSpacing(3);
  addText(`Role: ${offerData.role}`);
  addText(`Experience: ${offerData.experience}`);
  addText(`Location: ${offerData.city}`);
  addText(`CTC: ₹${offerData.ctc} LPA`);
  addSpacing(10);

  // Red Flags Section
  addText('RED FLAGS DETECTED', 14, true);
  addSpacing(3);
  
  if (redFlags.length === 0) {
    addText('✓ No red flags detected in your offer letter!');
  } else {
    redFlags.forEach((flag, index) => {
      addText(`${index + 1}. ${flag.title}`, 11, true);
      addText(`   Severity: ${flag.severity.toUpperCase()}`);
      addText(`   ${flag.description}`);
      if (flag.excerpt) {
        addText(`   Excerpt: "${flag.excerpt}"`);
      }
      addSpacing(3);
    });
  }
  addSpacing(10);

  // Salary Comparison Section
  addText('MARKET SALARY COMPARISON', 14, true);
  addSpacing(3);
  addText(`Market Range: ₹${salaryComparison.range.min} - ₹${salaryComparison.range.max} LPA`);
  addText(`Market Average: ₹${salaryComparison.range.avg} LPA`);
  addText(`Your Offer: ₹${offerData.ctc} LPA`);
  addText(`Comparison: ${salaryComparison.comparison.toUpperCase()}`);
  addText(salaryComparison.message);
  addSpacing(10);

  // Take-Home Salary Section
  addText('ESTIMATED TAKE-HOME', 14, true);
  addSpacing(3);
  addText(`Monthly Take-Home: ₹${takeHome.toLocaleString('en-IN')}`);
  addText('(Based on ~70% take-home ratio after deductions)');
  addSpacing(10);

  // Negotiation Suggestions Section
  addText('NEGOTIATION BLUEPRINT', 14, true);
  addSpacing(3);
  
  if (negotiationSuggestions.length === 0) {
    addText('No specific negotiation suggestions at this time.');
  } else {
    negotiationSuggestions.forEach((suggestion, index) => {
      addText(`${index + 1}. ${suggestion.suggestion}`, 11, true);
      addText(`   Priority: ${suggestion.priority.toUpperCase()}`);
      addText(`   Category: ${suggestion.category}`);
      addText(`   Reasoning: ${suggestion.reasoning}`);
      addSpacing(3);
    });
  }

  // Footer
  if (yPosition > 260) {
    doc.addPage();
    yPosition = 20;
  }
  yPosition = 280;
  doc.setFontSize(8);
  doc.setFont('helvetica', 'italic');
  doc.text('Generated by OfferLens - Decode your offer with confidence', margin, yPosition);

  // Save the PDF
  const fileName = `OfferLens_Analysis_${offerData.role.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.pdf`;
  doc.save(fileName);
}

export function generateAnalysisJSON(analysis: AnalysisResult): void {
  const jsonData = JSON.stringify(analysis, null, 2);
  const blob = new Blob([jsonData], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `OfferLens_Analysis_${analysis.offerData.role.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.json`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
